// Compiles docs/nag-section-*.md into supabase/functions/_shared/nagCorpus.generated.ts,
// the guideline text the antibiotic-suggest AI lookup is allowed to quote.
//
// Run after editing any docs/nag-section-*.md file:
//   node scripts/build-nag-corpus.ts
// (Node 22.18+ strips the TypeScript types natively.) src/test/nagCorpus.test.ts
// fails until this has been re-run, so a docs edit can't silently skip the bundle.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { splitNagMarkdown, type NagSection } from "../supabase/functions/_shared/nagCorpus.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = join(root, "docs");
const outPath = join(root, "supabase/functions/_shared/nagCorpus.generated.ts");

export function buildSections(): NagSection[] {
  return readdirSync(docsDir)
    .filter((f) => /^nag-section-.*\.md$/.test(f))
    .sort()
    .flatMap((f) => splitNagMarkdown(f.replace(/^nag-section-/, "").replace(/\.md$/, ""), readFileSync(join(docsDir, f), "utf8")));
}

export function renderGenerated(sections: NagSection[]): string {
  return [
    "// GENERATED by scripts/build-nag-corpus.ts from docs/nag-section-*.md — do not edit by hand.",
    'import type { NagSection } from "./nagCorpus.ts";',
    "",
    `export const NAG_CORPUS_SECTIONS: NagSection[] = ${JSON.stringify(sections, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sections = buildSections();
  writeFileSync(outPath, renderGenerated(sections));
  console.log(`Wrote ${sections.length} sections to ${outPath}`);
}
